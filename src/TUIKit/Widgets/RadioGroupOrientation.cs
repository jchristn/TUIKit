namespace TUIKit.Widgets
{
    /// <summary>The layout and arrow-key navigation axis of a radio group.</summary>
    public enum RadioGroupOrientation
    {
        /// <summary>One option per row, selected with Up/Down. The default.</summary>
        Vertical = 0,
        /// <summary>Options on one row, selected with Left/Right.</summary>
        Horizontal = 1
    }
}
