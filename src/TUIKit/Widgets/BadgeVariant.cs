namespace TUIKit.Widgets
{
    /// <summary>
    /// The color role of a <see cref="Badge"/>.
    /// </summary>
    public enum BadgeVariant
    {
        /// <summary>Neutral (muted) badge.</summary>
        Neutral = 0,

        /// <summary>Informational badge.</summary>
        Info = 1,

        /// <summary>Success badge.</summary>
        Success = 2,

        /// <summary>Warning badge.</summary>
        Warning = 3,

        /// <summary>Error badge.</summary>
        Error = 4,

        /// <summary>Accent badge.</summary>
        Accent = 5
    }
}
