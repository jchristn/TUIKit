namespace TUIKit.Widgets
{
    /// <summary>
    /// The axis along which a <see cref="SplitView"/> divides its area.
    /// </summary>
    public enum SplitOrientation
    {
        /// <summary>The children sit side by side, split along the horizontal axis.</summary>
        Horizontal = 0,

        /// <summary>The children stack, split along the vertical axis.</summary>
        Vertical = 1
    }
}
