namespace TUIKit.Widgets
{
    /// <summary>
    /// Horizontal alignment of a <see cref="Table"/> cell's content within its column.
    /// </summary>
    public enum CellAlignment
    {
        /// <summary>Align content to the left edge. The default.</summary>
        Left = 0,

        /// <summary>Center content within the column.</summary>
        Center = 1,

        /// <summary>Align content to the right edge.</summary>
        Right = 2
    }
}
